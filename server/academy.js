/* ------------------------------------------------------------
   Генератор по форме: цена идёт отрезками к заданным целям.
   follow(seed, старт, [[свечей, цель], ...], шум)
   ------------------------------------------------------------ */
function follow(seed, start, segs, vol, noise = 0.32) {
  const r = rng(seed);
  const out = [];
  let p = start;
  for (const [len, target] of segs) {
    const from = p;
    for (let k = 1; k <= len; k++) {
      const base = from + (target - from) * (k / len);
      const o = p;
      const c = base + (r() - 0.5) * 2 * vol * noise;
      out.push(K(o, Math.max(o, c) + r() * vol * 0.55, Math.min(o, c) - r() * vol * 0.55, c));
      p = c;
    }
  }
  return out;
}
const cont = (cs, seed, segs, vol, noise) => cs.push(...follow(seed, lastClose(cs), segs, vol, noise));

